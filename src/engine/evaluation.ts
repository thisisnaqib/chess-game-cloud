function squareToIndex(sq: Square, color: Color): number {
  const file = sq.charCodeAt(0) - 97; // a -> 0, h -> 7
  const rank = parseInt(sq[1], 10) - 1; // 1 -> 0, 8 -> 7
  // White table: index 0 is rank 8 (sq a8)
  if (color === 'w') {
    return (7 - rank) * 8 + file;
  }
  // Black table: mirror rank
  return rank * 8 + file;
}

/**
 * Evaluates the board position from the perspective of White.
 * Positive score = White is better, Negative score = Black is better.
 */
export function evaluateBoard(game: Chess): number {
  if (game.isCheckmate()) {
    return game.turn() === 'w' ? -Infinity : Infinity;
  }
  if (game.isDraw() || game.isStalemate() || game.isThreefoldRepetition()) {
    return 0;
  }

  let totalScore = 0;
  const board = game.board();

  for (let r = 0; r < 8; r++) {
    for (let c = 0; c < 8; c++) {
      const piece = board[r][c];
      if (piece) {
        const material = PIECE_VALUES[piece.type];
        const table = TABLES[piece.type];
        const tableIdx = squareToIndex(piece.square, piece.color);
        const positional = table ? table[tableIdx] : 0;

        const pieceTotal = material + positional;
        if (piece.color === 'w') {
          totalScore += pieceTotal;
        } else {
          totalScore -= pieceTotal;
        }
      }
    }
  }

  return totalScore;
}
